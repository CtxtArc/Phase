//! PHASE M5/M6: lowers PIR (phase_pir) to C source text (spec §6).
//!
//! Produces two strings per program: a header (struct typedefs + extern-fn
//! prototypes, meant to be shared with hand-written runtime glue like
//! `runtime/phase_runtime.c`) and a source file (the actual PHASE function
//! bodies). See spec §6.1-§6.2 for why C, not LLVM, and why buffers are
//! plain stack arrays in this simulation model.
//!
//! M6 adds simulated MMIO registers: each distinct register name from
//! `pir.mmio_registers` becomes a `volatile uint32_t` global. `volatile_read`/
//! `volatile_write` don't lower like ordinary calls -- they compile straight
//! to a read of, or assignment to, that global, so the actual safety
//! guarantee ("never reordered or eliminated") is enforced by the C
//! standard's own `volatile` semantics, not by anything this crate has to
//! independently prove.
//!
//! M8 adds real control flow: `PirInst::If`/`PirInst::While` lower to
//! actual C `if`/`while` statements (indentation-tracked, arbitrarily
//! nested), closing the "straight-line only" scope cut from M5.
//!
//! M11 lets `volatile_read(REG @MMIO)` appear directly in a condition/
//! assignment RHS (`PirExpr::VolatileRead`): it compiles to a bare read
//! of the same `volatile` global CallAssign's volatile_read case already
//! uses, so a real polling loop's condition is re-read the C standard's
//! own `volatile` semantics every iteration, not memoized by mistake.

use phase_ast::{BinOp, BorrowMode, Domain};
use phase_pir::{
    CallArg, PirEntityDef, PirExpr, PirFn, PirFnSig, PirInst, PirLiteral, PirProgram, PirType,
};
use std::collections::{HashMap, HashSet};

pub struct Generated {
    pub header: String,
    pub source: String,
}

/// `stem` becomes both the `#ifndef` guard and the `#include` name the
/// generated source uses for its own header (e.g. `"radio_pipeline"` ->
/// `radio_pipeline.gen.h`, guard `PHASE_GEN_RADIO_PIPELINE_H`).
pub fn generate(program: &PirProgram, stem: &str) -> Generated {
    Generated {
        header: generate_header(program, stem),
        source: generate_source(program, stem, false),
    }
}

/// Like [`generate`], but the source is instrumented with runtime ownership
/// checks (`runtime/phase_check.h`) and must be linked with
/// `runtime/phase_check.c`. The header is identical to [`generate`]'s.
pub fn generate_checked(program: &PirProgram, stem: &str) -> Generated {
    Generated {
        header: generate_header(program, stem),
        source: generate_source(program, stem, true),
    }
}

/// Placeholder bodies for every `extern fn` in `program`, for trying a
/// program (or fuzzing one) without hand-written runtime C.
///
/// Buffer and entity parameters are left untouched; scalar returns come from
/// a small PRNG seeded by the `PHASE_STUB_SEED` environment variable
/// (default 1), so `bool`/integer results drive different paths through the
/// same binary run to run. Integers are kept small (0-3) so loop bounds stay
/// short.
pub fn generate_stubs(program: &PirProgram, stem: &str) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "/* Stub extern fns for {stem}, generated by `phase build --stub-externs`. */\n"
    ));
    out.push_str(&format!("#include \"{stem}.gen.h\"\n"));
    out.push_str("#include <stdlib.h>\n\n");
    out.push_str(
        "/* Not every program has an extern that needs a random result. */\n#if defined(__GNUC__)\n__attribute__((unused))\n#endif\nstatic unsigned long phase_stub_next(void) {\n    static unsigned long state = 0;\n    if (state == 0) {\n        const char *seed = getenv(\"PHASE_STUB_SEED\");\n        state = seed ? strtoul(seed, NULL, 10) * 2654435761UL + 1 : 1;\n    }\n    state ^= state << 13;\n    state ^= state >> 7;\n    state ^= state << 17;\n    return state;\n}\n\n",
    );
    for sig in &program.extern_fns {
        let mut body = String::new();
        for (name, ty) in &sig.params {
            body.push_str(&format!("    (void){name};\n"));
            if matches!(ty, PirType::Buffer { .. }) {
                body.push_str(&format!("    (void){name}_len;\n"));
            }
        }
        match &sig.return_type {
            None => {}
            Some(PirType::Scalar(c)) if c == "bool" => {
                body.push_str("    return (phase_stub_next() & 1) != 0;\n")
            }
            Some(PirType::Scalar(c)) if c == "float" || c == "double" => body.push_str(&format!(
                "    return ({c})(phase_stub_next() % 100) / 100;\n"
            )),
            Some(PirType::Scalar(c)) => {
                body.push_str(&format!("    return ({c})(phase_stub_next() % 4);\n"))
            }
            Some(other) => body.push_str(&format!("    return ({}){{0}};\n", type_name(other))),
        }
        let proto = format_fn_prototype(sig);
        let proto = proto.trim_end().trim_end_matches(';');
        out.push_str(&format!("{proto} {{\n{body}}}\n\n"));
    }
    out
}

// ---- type formatting ------------------------------------------------------

/// The type name usable in a *non-declarator* context (return types,
/// buffer element types nested inside a struct field's own declarator,
/// etc). Not valid on its own for a buffer variable -- see `declare`.
fn type_name(ty: &PirType) -> String {
    match ty {
        PirType::Scalar(s) => s.clone(),
        PirType::Named(n) => n.clone(),
        PirType::Buffer { elem, .. } => type_name(elem),
    }
}

/// Emit a full C declaration for a named variable/field of the given PIR
/// type, handling the array-declarator wrapping C requires for buffers
/// (`Sample name[1024];`, not `buffer<Sample,1024> name;`).
/// A buffer's element count as a C expression: the constant for a fixed
/// length, or the `<name>_len` companion of a `buffer<T, _>` parameter (or
/// of a borrow of one).
fn len_expr(name: &str, len: Option<u64>) -> String {
    match len {
        Some(n) => n.to_string(),
        None => format!("{name}_len"),
    }
}

fn declare(name: &str, ty: &PirType) -> String {
    match ty {
        PirType::Buffer { elem, len: Some(n) } => format!("{} {}[{}]", type_name(elem), name, n),
        // Only parameters have a run-time length; they are pointers.
        PirType::Buffer { elem, len: None } => format!("{}* {}", type_name(elem), name),
        other => format!("{} {}", type_name(other), name),
    }
}

// ---- header: struct typedefs + extern fn prototypes -----------------------

fn generate_header(program: &PirProgram, stem: &str) -> String {
    let guard = format!("PHASE_GEN_{}_H", stem.to_uppercase());
    let mut out = String::new();
    out.push_str(&format!("#ifndef {guard}\n#define {guard}\n\n"));
    out.push_str("#include <stdint.h>\n#include <stddef.h>\n#include <stdbool.h>\n\n");

    if !program.entities.is_empty() {
        out.push_str("/* --- entity struct definitions (from `entity` declarations) --- */\n\n");
        for e in &program.entities {
            out.push_str(&format_struct(e));
            out.push('\n');
        }
    }

    if !program.extern_fns.is_empty() {
        out.push_str("/* --- extern fn prototypes ---\n");
        out.push_str(" * PHASE `extern fn` declares a trusted, opaque operation implemented\n");
        out.push_str(" * elsewhere (e.g. runtime/phase_runtime.c for this demo) -- the compiler\n");
        out.push_str(" * only emits a matching prototype here, never a body.\n");
        out.push_str(
            " * Convention: every `buffer<T,N>` argument gets a trailing `size_t ..._len`\n",
        );
        out.push_str(" * parameter carrying its compile-time-known element count.\n */\n\n");
        for f in &program.extern_fns {
            out.push_str(&format_fn_prototype(f));
            out.push_str(";\n");
        }
        out.push('\n');
    }

    if !program.mmio_registers.is_empty() {
        out.push_str("/* --- simulated MMIO registers (M6) ---\n");
        out.push_str(
            " * The host simulation has no real memory-mapped hardware, so each register\n",
        );
        out.push_str(" * name used with `volatile_read`/`volatile_write` becomes one `volatile`\n");
        out.push_str(" * global. `volatile` is what makes the compiler's own \"never reordered\n");
        out.push_str(" * or eliminated\" guarantee (spec bug-gallery #7) real rather than a\n");
        out.push_str(" * documentation-only claim -- it's enforced by the C standard itself.\n");
        out.push_str(" * Every simulated register has the same width (uint32_t); see\n");
        out.push_str(" * phase_specification.md for why.\n */\n\n");
        for reg in &program.mmio_registers {
            out.push_str(&format!("extern volatile uint32_t {reg};\n"));
        }
        out.push('\n');
    }

    out.push_str(&format!("#endif /* {guard} */\n"));
    out
}

fn format_struct(e: &PirEntityDef) -> String {
    let mut s = "typedef struct {\n".to_string();
    for (fname, fty) in &e.fields {
        s.push_str(&format!("    {};\n", declare(fname, fty)));
    }
    s.push_str(&format!("}} {};\n", e.name));
    s
}

fn format_fn_prototype(sig: &PirFnSig) -> String {
    let ret = sig
        .return_type
        .as_ref()
        .map(type_name)
        .unwrap_or_else(|| "void".to_string());
    let params = format_params(sig);
    format!("{ret} {}({params})", sig.name)
}

fn format_params(sig: &PirFnSig) -> String {
    if sig.params.is_empty() {
        return "void".to_string();
    }
    let mut parts = Vec::new();
    for (i, (name, ty)) in sig.params.iter().enumerate() {
        match ty {
            PirType::Buffer { elem, .. } => {
                // `read` parameters are `const`, so the C compiler itself
                // rejects an extern body that writes through one.
                let const_kw = if sig.read_only.get(i).copied().unwrap_or(false) {
                    "const "
                } else {
                    ""
                };
                parts.push(format!("{const_kw}{}* {}", type_name(elem), name));
                parts.push(format!("size_t {}_len", name));
            }
            other => parts.push(declare(name, other)),
        }
    }
    parts.join(", ")
}

// ---- source: PHASE fn bodies -----------------------------------------------

fn generate_source(program: &PirProgram, stem: &str, checked: bool) -> String {
    let mut out = String::new();
    out.push_str(&format!("#include \"{stem}.gen.h\"\n"));
    out.push_str("#include \"phase_runtime.h\"\n");
    if checked {
        out.push_str("#include \"phase_check.h\"\n");
    }
    out.push('\n');
    out.push_str("/* Generated by the PHASE compiler. Do not edit by hand. */\n");
    if checked {
        out.push_str(
            "/* Checked build: every ownership-relevant operation is verified at run\n * time against a shadow state (runtime/phase_check.h). */\n",
        );
    }
    out.push('\n');

    if !program.mmio_registers.is_empty() {
        out.push_str("/* Storage for the simulated MMIO registers declared in the header. */\n");
        for reg in &program.mmio_registers {
            out.push_str(&format!("volatile uint32_t {reg};\n"));
        }
        out.push('\n');
    }

    // name -> signature, for both extern fns and other PHASE fns, so a
    // call site knows whether to append a `_len` argument for a buffer.
    let mut sigs: HashMap<&str, &PirFnSig> = HashMap::new();
    for f in &program.extern_fns {
        sigs.insert(f.name.as_str(), f);
    }
    for f in &program.fns {
        sigs.insert(f.sig.name.as_str(), &f.sig);
    }
    let externs: HashSet<&str> = program.extern_fns.iter().map(|f| f.name.as_str()).collect();

    for f in &program.fns {
        out.push_str(&format_fn(f, &sigs, &externs, checked));
        out.push('\n');
    }

    out
}

/// Something that goes out of scope at the end of a block, for the checked
/// build's scope-exit checks.
enum ScopeItem {
    /// A buffer's storage: the C expression for its address, and its name.
    Storage(String, String),
    /// A borrow handle (its `<name>__h` id).
    Handle(String),
    /// A typestate value: the C expression for its address, and its name.
    TsValue(String, String),
}

/// Per-function state while emitting C.
struct FnCx<'a> {
    sigs: &'a HashMap<&'a str, &'a PirFnSig>,
    externs: &'a HashSet<&'a str>,
    sig: &'a PirFnSig,
    locals: HashMap<String, PirType>,
    swapped: HashSet<String>,
    checked: bool,
    /// Buffer borrow handles in scope, with their mode.
    handles: HashMap<String, BorrowMode>,
    /// Borrow handles of non-buffer entities (C pointers to the value).
    struct_handles: HashSet<String>,
    /// One entry per open block, innermost last.
    scopes: Vec<Vec<ScopeItem>>,
}

fn c_domain(d: Domain) -> &'static str {
    match d {
        Domain::Ram => "PHASE_DOM_RAM",
        Domain::Stack => "PHASE_DOM_STACK",
        Domain::Dma => "PHASE_DOM_DMA",
        Domain::Mmio => "PHASE_DOM_MMIO",
        Domain::Device => "PHASE_DOM_DEVICE",
    }
}

impl FnCx<'_> {
    fn is_buffer(&self, name: &str) -> bool {
        matches!(self.locals.get(name), Some(PirType::Buffer { .. }))
    }

    /// The runtime key of a typestate value: the address of the variable
    /// holding it -- or, for a borrow handle, the address it points to.
    fn ts_key(&self, name: &str) -> String {
        if self.struct_handles.contains(name) {
            format!("(const void *){name}")
        } else {
            format!("&{name}")
        }
    }

    /// Start tracking typestate value `name` in the current scope.
    fn track_ts(&mut self, name: &str) {
        let key = format!("&{name}");
        if let Some(scope) = self.scopes.last_mut() {
            scope.push(ScopeItem::TsValue(key, name.to_string()));
        }
    }

    /// Checks for one scope's items going out of scope.
    fn scope_end_checks(items: &[ScopeItem], pad: &str) -> String {
        let mut s = String::new();
        for item in items.iter().rev() {
            match item {
                ScopeItem::Handle(h) => {
                    s.push_str(&format!("{pad}phase_chk_handle_end({h}__h, \"{h}\");\n"))
                }
                ScopeItem::Storage(addr, name) => {
                    s.push_str(&format!("{pad}phase_chk_scope_end({addr}, \"{name}\");\n"))
                }
                ScopeItem::TsValue(addr, name) => {
                    s.push_str(&format!("{pad}phase_chk_ts_end({addr}, \"{name}\");\n"))
                }
            }
        }
        s
    }

    /// Parameters must be in the domain their signature promises.
    fn param_exit_checks(&self, pad: &str) -> String {
        let mut s = String::new();
        for (i, (pname, pty)) in self.sig.params.iter().enumerate() {
            if !matches!(pty, PirType::Buffer { .. }) {
                continue;
            }
            let entry = self.sig.param_domains.get(i).copied().flatten();
            let after = self.sig.param_domains_after.get(i).copied().flatten();
            if let Some(d) = after.or(entry) {
                s.push_str(&format!(
                    "{pad}phase_chk_param_exit({pname}, {}, \"{}\", \"{pname}\");\n",
                    c_domain(d),
                    self.sig.name
                ));
            }
        }
        s
    }

    /// Everything a `return` (or the end of the function) must check.
    fn exit_checks(&self, pad: &str) -> String {
        let mut s = self.param_exit_checks(pad);
        for scope in self.scopes.iter().rev() {
            s.push_str(&Self::scope_end_checks(scope, pad));
        }
        if self.sig.name != "main" {
            s.push_str(&format!("{pad}phase_chk_leave();\n"));
        }
        s
    }

    /// Checked-build instrumentation around a call: argument checks before
    /// it, domain changes made by an extern after it.
    fn call_checks(&self, callee: &str, args: &[CallArg], pad: &str) -> (String, String) {
        let mut before = String::new();
        let mut after = String::new();
        let Some(sig) = self.sigs.get(callee) else {
            return (before, after);
        };
        let mut alias_ptrs = Vec::new();
        let mut alias_ro = Vec::new();
        for (i, arg) in args.iter().enumerate() {
            let CallArg::Entity(name) = arg else { continue };
            if let Some(Some(state)) = sig.param_states.get(i) {
                let consume = sig.param_access.get(i).copied().flatten() != Some(BorrowMode::Read);
                before.push_str(&format!(
                    "{pad}phase_chk_ts_use({}, \"{state}\", {}, \"{callee}\", \"{name}\");\n",
                    self.ts_key(name),
                    if consume { 1 } else { 0 }
                ));
            }
            if !self.is_buffer(name) {
                continue;
            }
            let via = match self.handles.get(name) {
                Some(BorrowMode::Read) => "PHASE_VIA_READ_BORROW",
                Some(BorrowMode::Write) => "PHASE_VIA_WRITE_BORROW",
                None => "PHASE_VIA_OWNER",
            };
            if self.handles.contains_key(name) {
                before.push_str(&format!(
                    "{pad}phase_chk_handle_use({name}__h, \"{name}\");\n"
                ));
            }
            let domain = sig
                .param_domains
                .get(i)
                .copied()
                .flatten()
                .map(c_domain)
                .unwrap_or("-1");
            let access = sig.param_access.get(i).copied().flatten();
            let access_c = match access {
                Some(BorrowMode::Read) => "PHASE_ACC_READ",
                Some(BorrowMode::Write) => "PHASE_ACC_WRITE",
                None => "PHASE_ACC_NONE",
            };
            // The size the callee will believe the buffer has: its declared
            // length, or -- for a `_` parameter -- the length it is passed.
            let told = match sig.params.get(i).map(|(_, t)| t) {
                Some(PirType::Buffer { elem, len }) => {
                    let n = match len {
                        Some(n) => n.to_string(),
                        None => match self.locals.get(name) {
                            Some(PirType::Buffer { len, .. }) => len_expr(name, *len),
                            _ => format!("sizeof({name})/sizeof({name}[0])"),
                        },
                    };
                    format!("(size_t)({n}) * sizeof({})", type_name(elem))
                }
                _ => format!("sizeof({name})"),
            };
            before.push_str(&format!(
                "{pad}phase_chk_arg({name}, {told}, {via}, {domain}, {access_c}, \"{callee}\", \"{name}\");\n"
            ));
            alias_ptrs.push(name.clone());
            let ro = access == Some(BorrowMode::Read)
                || self.handles.get(name) == Some(&BorrowMode::Read);
            alias_ro.push(if ro { "1" } else { "0" });

            // An extern is trusted to perform its declared domain change;
            // a PHASE function's body performs (and is checked for) its own.
            if self.externs.contains(callee) {
                if let Some(Some(to)) = sig.param_domains_after.get(i) {
                    after.push_str(&format!(
                        "{pad}phase_chk_transfer({name}, {}, \"{callee}\", \"{name}\");\n",
                        c_domain(*to)
                    ));
                }
            }
        }
        if alias_ptrs.len() > 1 {
            before.push_str(&format!(
                "{pad}{{ const void *const phase_args[] = {{{}}}; const int phase_ro[] = {{{}}}; phase_chk_alias(\"{callee}\", {}, phase_args, phase_ro); }}\n",
                alias_ptrs.join(", "),
                alias_ro.join(", "),
                alias_ptrs.len()
            ));
        }
        (before, after)
    }
}

fn format_fn(
    f: &PirFn,
    sigs: &HashMap<&str, &PirFnSig>,
    externs: &HashSet<&str>,
    checked: bool,
) -> String {
    let is_main = f.sig.name == "main";
    let (ret, name, params) = if is_main {
        ("int".to_string(), "main".to_string(), "void".to_string())
    } else {
        let ret = f
            .sig
            .return_type
            .as_ref()
            .map(type_name)
            .unwrap_or_else(|| "void".to_string());
        (ret, f.sig.name.clone(), format_params(&f.sig))
    };

    let mut out = format!("{ret} {name}({params}) {{\n");
    if checked && !is_main {
        out.push_str("    phase_chk_enter();\n");
    }
    let mut cx = FnCx {
        sigs,
        externs,
        sig: &f.sig,
        locals: f.sig.params.iter().cloned().collect(),
        swapped: swapped_buffers(&f.body),
        checked,
        handles: HashMap::new(),
        struct_handles: HashSet::new(),
        scopes: vec![Vec::new()],
    };
    if checked {
        // A typestate parameter arrives in the state its signature names
        // (the caller's check verified that).
        for (i, (pname, _)) in f.sig.params.iter().enumerate() {
            if let Some(Some(state)) = f.sig.param_states.get(i) {
                out.push_str(&format!(
                    "    phase_chk_ts_set(&{pname}, \"{state}\", \"{pname}\");\n"
                ));
                cx.track_ts(pname);
            }
        }
    }
    for inst in &f.body {
        out.push_str(&format_inst(inst, &mut cx, 1));
    }
    if checked {
        out.push_str(&cx.exit_checks("    "));
    }
    if is_main {
        out.push_str("    return 0;\n");
    }
    out.push_str("}\n");
    out
}

/// Every buffer named in a `swap` anywhere in `body`. These are emitted as
/// a storage array plus a pointer to it, so a swap exchanges pointers
/// instead of copying contents.
fn swapped_buffers(body: &[PirInst]) -> HashSet<String> {
    let mut out = HashSet::new();
    for inst in body {
        match inst {
            PirInst::Swap { a, b } => {
                out.insert(a.clone());
                out.insert(b.clone());
            }
            PirInst::If {
                then_body,
                else_body,
                ..
            } => {
                out.extend(swapped_buffers(then_body));
                out.extend(swapped_buffers(else_body));
            }
            PirInst::While { body, .. } => out.extend(swapped_buffers(body)),
            _ => {}
        }
    }
    out
}

/// A nested block (`if`/`else`/`while` body): its own scope, closed with
/// scope-exit checks in a checked build.
fn format_block(insts: &[PirInst], cx: &mut FnCx, indent: usize) -> String {
    cx.scopes.push(Vec::new());
    let mut s = String::new();
    for inst in insts {
        s.push_str(&format_inst(inst, cx, indent));
    }
    let scope = cx.scopes.pop().unwrap_or_default();
    if cx.checked {
        s.push_str(&FnCx::scope_end_checks(&scope, &"    ".repeat(indent)));
    }
    for item in &scope {
        if let ScopeItem::Handle(h) = item {
            cx.handles.remove(h);
        }
    }
    s
}

fn format_inst(inst: &PirInst, cx: &mut FnCx, indent: usize) -> String {
    let pad = "    ".repeat(indent);
    match inst {
        PirInst::EntityCreate { name, ty, domain } => {
            cx.locals.insert(name.clone(), ty.clone());
            let (mut s, storage) = match ty {
                PirType::Buffer { elem, len } if cx.swapped.contains(name) => {
                    let elem = type_name(elem);
                    let len = len.unwrap_or_default();
                    (
                        format!(
                            "{pad}{elem} {name}__storage[{len}];\n{pad}{elem}* {name} = {name}__storage; /* swappable: see `swap` */\n"
                        ),
                        format!("{name}__storage"),
                    )
                }
                _ => (format!("{pad}{};\n", declare(name, ty)), name.clone()),
            };
            if cx.checked && matches!(ty, PirType::Buffer { .. }) {
                let d = c_domain(domain.unwrap_or(Domain::Ram));
                s.push_str(&format!(
                    "{pad}phase_chk_create({storage}, sizeof({storage}), {d}, \"{name}\");\n"
                ));
                if let Some(scope) = cx.scopes.last_mut() {
                    scope.push(ScopeItem::Storage(storage, name.clone()));
                }
            }
            s
        }

        PirInst::TypestateInit {
            name,
            state,
            initial,
        } => {
            if !cx.checked {
                return String::new();
            }
            cx.track_ts(name);
            format!("{pad}phase_chk_ts_fresh(&{name}, \"{state}\", \"{initial}\", \"{name}\");\n")
        }

        PirInst::Swap { a, b } => {
            let elem = match cx.locals.get(a) {
                Some(PirType::Buffer { elem, .. }) => type_name(elem),
                _ => "void".to_string(),
            };
            let mut s = String::new();
            if cx.checked {
                s.push_str(&format!(
                    "{pad}phase_chk_swap({a}, {b}, \"{a}\", \"{b}\");\n"
                ));
            }
            s.push_str(&format!(
                "{pad}{{ /* swap {a}, {b} */ {elem}* phase_swap_tmp = {a}; {a} = {b}; {b} = phase_swap_tmp; }}\n"
            ));
            s
        }

        PirInst::EntityCreateWithFields {
            name, ty, fields, ..
        } => {
            cx.locals.insert(name.clone(), ty.clone());
            let inits: Vec<String> = fields
                .iter()
                .map(|(fname, lit)| format!(".{fname} = {}", format_literal(lit)))
                .collect();
            format!("{pad}{} = {{ {} }};\n", declare(name, ty), inits.join(", "))
        }

        PirInst::EntityCreateWithLiteral {
            name, ty, value, ..
        } => {
            cx.locals.insert(name.clone(), ty.clone());
            format!("{pad}{} = {};\n", declare(name, ty), format_literal(value))
        }

        PirInst::CallAssign {
            name,
            ty,
            callee,
            args,
            ..
        } => {
            cx.locals.insert(name.clone(), ty.clone());
            if callee == "volatile_read" {
                // M6: not a function call at all -- a direct read of the
                // `volatile` global. The C standard guarantees this can't
                // be reordered past another volatile access or eliminated,
                // which is the actual mechanism behind the "never
                // reordered or eliminated" claim (bug-gallery #7).
                let reg = match args.first() {
                    Some(CallArg::MmioRegister(r)) => r.clone(),
                    _ => {
                        "/* internal error: volatile_read missing MMIO register arg */".to_string()
                    }
                };
                return format!("{pad}{} = {reg};\n", declare(name, ty));
            }
            let call_sig = cx.sigs.get(callee.as_str()).copied();
            let arg_text = format_args(args, call_sig, &cx.locals, &cx.struct_handles);
            let (before, mut after) = if cx.checked {
                cx.call_checks(callee, args, &pad)
            } else {
                Default::default()
            };
            // The result's state is the callee's *declared* return state.
            if cx.checked {
                if let Some(state) = call_sig.and_then(|s| s.return_state.clone()) {
                    after.push_str(&format!(
                        "{pad}phase_chk_ts_set(&{name}, \"{state}\", \"{name}\");\n"
                    ));
                    cx.track_ts(name);
                }
            }
            format!(
                "{before}{pad}{} = {}({});\n{after}",
                declare(name, ty),
                callee,
                arg_text
            )
        }

        PirInst::EntityMove { name, to } => {
            let mut s = format!(
                "{pad}/* move {name} -> @{} (compile-time only; the simulation model keeps everything in one address space, so there is nothing to physically move) */\n",
                to.name()
            );
            if cx.checked && cx.is_buffer(name) {
                s.push_str(&format!(
                    "{pad}phase_chk_move({name}, {}, \"{name}\");\n",
                    c_domain(*to)
                ));
            }
            s
        }

        PirInst::EntitySync { name, from } => {
            let wait_fn = match from {
                Domain::Dma => "sim_dma_wait",
                Domain::Device => "sim_device_wait",
                // The M2 analyzer guarantees `sync` is only legal from
                // Dma/Device; anything else here is unreachable in a
                // program that passed analysis, but fall back safely.
                _ => "sim_device_wait",
            };
            // A buffer parameter is a pointer in C, so `sizeof` would give the
            // pointer's size; use the compile-time length instead.
            let nbytes = match cx.locals.get(name) {
                Some(PirType::Buffer { len, .. }) => {
                    format!("{} * sizeof({name}[0])", len_expr(name, *len))
                }
                _ => format!("sizeof({name})"),
            };
            let mut s = String::new();
            if cx.checked && cx.is_buffer(name) {
                s.push_str(&format!("{pad}phase_chk_sync({name}, \"{name}\");\n"));
            }
            s.push_str(&format!("{pad}{wait_fn}(\"{name}\", {name}, {nbytes});\n"));
            s
        }

        PirInst::EntityBorrow { name, target, mode } => {
            let target_ty = cx.locals.get(target).cloned();
            let (elem_ty, is_buffer) = match &target_ty {
                Some(PirType::Buffer { elem, .. }) => (type_name(elem), true),
                Some(other) => (type_name(other), false),
                None => ("void".to_string(), false),
            };
            let const_kw = match mode {
                BorrowMode::Read => "const ",
                BorrowMode::Write => "",
            };
            let ptr_ty = format!("{const_kw}{elem_ty}*");
            cx.locals.insert(
                name.clone(),
                target_ty.clone().unwrap_or(PirType::Scalar("void".into())),
            );
            if is_buffer {
                let mut s = format!("{pad}{ptr_ty} {name} = {target}; /* borrow */\n");
                // A borrow of a run-time-length buffer carries the length too.
                if let Some(PirType::Buffer { len: None, .. }) = &target_ty {
                    s.push_str(&format!("{pad}size_t {name}_len = {target}_len;\n"));
                }
                if cx.checked {
                    let write = if *mode == BorrowMode::Write { 1 } else { 0 };
                    s.push_str(&format!(
                        "{pad}int {name}__h = phase_chk_borrow({target}, {write}, \"{name}\");\n"
                    ));
                    cx.handles.insert(name.clone(), *mode);
                    if let Some(scope) = cx.scopes.last_mut() {
                        scope.push(ScopeItem::Handle(name.clone()));
                    }
                }
                s
            } else {
                cx.struct_handles.insert(name.clone());
                format!("{pad}{ptr_ty} {name} = &{target}; /* borrow */\n")
            }
        }

        PirInst::EntityRelease { name } => {
            let mut s = format!(
                "{pad}/* release {name} (compile-time only; no separate runtime action) */\n"
            );
            if cx.checked && cx.handles.contains_key(name) {
                s.push_str(&format!("{pad}phase_chk_release({name}__h, \"{name}\");\n"));
            }
            s
        }

        PirInst::EntityDestroy { name } => {
            let mut s = format!(
                "{pad}/* destroy {name} (compile-time only; buffers are stack-allocated, so there is no separate deallocation step) */\n"
            );
            if cx.checked && cx.is_buffer(name) {
                s.push_str(&format!("{pad}phase_chk_destroy({name}, \"{name}\");\n"));
            }
            s
        }

        PirInst::Call { callee, args } => {
            if callee == "volatile_write" {
                // M6: not a function call -- a direct assignment to the
                // `volatile` global. Same reasoning as volatile_read above.
                let reg = match args.first() {
                    Some(CallArg::MmioRegister(r)) => r.clone(),
                    _ => {
                        "/* internal error: volatile_write missing MMIO register arg */".to_string()
                    }
                };
                let value = match args.get(1) {
                    Some(CallArg::Entity(n)) => n.clone(),
                    Some(CallArg::Literal(lit)) => format_literal(lit),
                    Some(CallArg::MmioRegister(r)) => r.clone(),
                    None => "/* internal error: volatile_write missing value arg */".to_string(),
                };
                return format!("{pad}{reg} = {value};\n");
            }
            let call_sig = cx.sigs.get(callee.as_str()).copied();
            let arg_text = format_args(args, call_sig, &cx.locals, &cx.struct_handles);
            let (before, after) = if cx.checked {
                cx.call_checks(callee, args, &pad)
            } else {
                Default::default()
            };
            format!("{before}{pad}{callee}({arg_text});\n{after}")
        }

        PirInst::Return { value } => {
            let mut checks = String::new();
            if cx.checked {
                // Returning a typestate value hands it to the caller: it
                // must be in the declared state, and is consumed here.
                if let (Some(v), Some(state)) = (value, &cx.sig.return_state) {
                    checks.push_str(&format!(
                        "{pad}phase_chk_ts_use({}, \"{state}\", 1, \"{}\", \"{v}\");\n",
                        cx.ts_key(v),
                        cx.sig.name
                    ));
                }
                checks.push_str(&cx.exit_checks(&pad));
            }
            match value {
                Some(v) => format!("{checks}{pad}return {v};\n"),
                // PHASE's `main` is C's `int main(void)`: a bare `return;`
                // there would leave the exit status undefined.
                None if cx.sig.name == "main" => format!("{checks}{pad}return 0;\n"),
                None => format!("{checks}{pad}return;\n"),
            }
        }

        // ---- M8: real control flow ----------------------------------------
        PirInst::If {
            cond,
            then_body,
            else_body,
        } => {
            let mut s = format!("{pad}if ({}) {{\n", format_pir_expr(cond));
            s.push_str(&format_block(then_body, cx, indent + 1));
            if else_body.is_empty() {
                s.push_str(&format!("{pad}}}\n"));
            } else {
                s.push_str(&format!("{pad}}} else {{\n"));
                s.push_str(&format_block(else_body, cx, indent + 1));
                s.push_str(&format!("{pad}}}\n"));
            }
            s
        }

        PirInst::While { cond, body } => {
            let mut s = format!("{pad}while ({}) {{\n", format_pir_expr(cond));
            s.push_str(&format_block(body, cx, indent + 1));
            s.push_str(&format!("{pad}}}\n"));
            s
        }

        // ---- M9: assignment ------------------------------------------------
        PirInst::Assign { name, value } => {
            format!("{pad}{name} = {};\n", format_pir_expr(value))
        }
    }
}

/// Format an `if`/`while` condition (`PirExpr`) as a C boolean expression.
/// Every `Binary` node is fully parenthesized -- simplest way to guarantee
/// correct precedence without implementing a precedence table, at the
/// (acceptable, for generated code) cost of some redundant parens.
fn format_pir_expr(e: &PirExpr) -> String {
    match e {
        PirExpr::Ident(n) => n.clone(),
        PirExpr::IntLit(n) => n.to_string(),
        PirExpr::FloatLit(n) => format!("{n}f"),
        PirExpr::BoolLit(b) => b.to_string(),
        PirExpr::Binary { op, lhs, rhs } => format!(
            "({} {} {})",
            format_pir_expr(lhs),
            format_binop(*op),
            format_pir_expr(rhs)
        ),
        // M11: not a function call -- a direct read of the `volatile`
        // global, same reasoning as CallAssign's volatile_read special
        // case (see format_inst below). This is what makes it safe to
        // read the same register on every loop iteration: the C standard
        // itself forbids hoisting a `volatile` read out of a loop.
        PirExpr::VolatileRead { register } => register.clone(),
    }
}

fn format_binop(op: BinOp) -> &'static str {
    match op {
        BinOp::Add => "+",
        BinOp::Sub => "-",
        BinOp::Mul => "*",
        BinOp::Div => "/",
        BinOp::Eq => "==",
        BinOp::NotEq => "!=",
        BinOp::Lt => "<",
        BinOp::Gt => ">",
        BinOp::LtEq => "<=",
        BinOp::GtEq => ">=",
    }
}

fn format_args(
    args: &[CallArg],
    sig: Option<&PirFnSig>,
    locals: &HashMap<String, PirType>,
    struct_handles: &HashSet<String>,
) -> String {
    let mut parts = Vec::new();
    for (i, a) in args.iter().enumerate() {
        match a {
            CallArg::Entity(name) => {
                // A borrow of a (non-buffer) entity is a C pointer to it,
                // but entity parameters take the value.
                if struct_handles.contains(name) {
                    parts.push(format!("*{name}"));
                } else {
                    parts.push(name.clone());
                }
                // Append the compile-time element count for any argument
                // whose *declared parameter* is a buffer -- matches the
                // trailing `size_t ..._len` convention in format_params.
                let param_is_buffer = sig
                    .and_then(|s| s.params.get(i))
                    .map(|(_, ty)| matches!(ty, PirType::Buffer { .. }))
                    .unwrap_or(false);
                if param_is_buffer {
                    if let Some(PirType::Buffer { len, .. }) = locals.get(name) {
                        parts.push(len_expr(name, *len));
                    } else {
                        parts.push(format!("sizeof({name})/sizeof({name}[0])"));
                    }
                }
            }
            CallArg::Literal(lit) => parts.push(format_literal(lit)),
            CallArg::MmioRegister(name) => parts.push(name.clone()),
        }
    }
    parts.join(", ")
}

fn format_literal(lit: &PirLiteral) -> String {
    match lit {
        PirLiteral::Int(n) => n.to_string(),
        PirLiteral::Float(n) => format!("{n}f"),
        PirLiteral::Str(s) => format!("{s:?}"),
        PirLiteral::Bool(b) => b.to_string(),
    }
}

